import React, { useState, useRef, useEffect } from 'react';
import { Item } from '../types';
import { Button } from '../components/Button';
import { SquircleContainer } from '../components/SquircleContainer';
import { motion } from 'framer-motion';
import { sanitizeString, MAX_TITLE_LENGTH } from '../utils/security';

interface ResultScreenProps {
  items: Item[]; // Assumed sorted. Shorter than totalCount for a Top N.
  totalCount: number;
  onContinue: () => void;
  onReset: () => void;
  onRestart: () => void;
}

export const ResultScreen: React.FC<ResultScreenProps> = ({ items, totalCount, onContinue, onReset, onRestart }) => {
  const [isCopied, setIsCopied] = useState(false);
  // A Top N: the user stopped before every item was placed
  const isPartial = items.length < totalCount;
  const defaultTitle = isPartial ? `Your Top ${items.length}` : "Your Ranking";
  const [title, setTitle] = useState(defaultTitle);
  const [isEditing, setIsEditing] = useState(false);
  const titleInputRef = useRef<HTMLInputElement>(null);
  const isImageRanking = items.some(item => item.imageUrl);

  // Capture date once on mount
  const [dateString] = useState(() => {
    const now = new Date();
    const date = now.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' });
    const time = now.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: false });
    return `${date} • ${time}`;
  });

  useEffect(() => {
    if (isEditing && titleInputRef.current) {
      titleInputRef.current.focus();
    }
  }, [isEditing]);

  const handleTitleSubmit = () => {
    setIsEditing(false);

    // Sanitize title on submit
    const cleanTitle = sanitizeString(title, MAX_TITLE_LENGTH);

    if (cleanTitle === "") {
      setTitle(defaultTitle);
    } else {
      setTitle(cleanTitle);
    }
  };

  const handleCopyToClipboard = async () => {
    const listText = items
      .map((item, index) => `${(index + 1).toString().padStart(2, '0')}. ${item.label}`)
      .join('\n');

    const scope = isPartial ? `Top ${items.length} of ${totalCount}. ` : '';
    const textToCopy = `${title}\n${scope}Ranked on ${dateString}\n\n${listText}\n\nGenerated by The Order`;

    try {
      await navigator.clipboard.writeText(textToCopy);
      setIsCopied(true);
      setTimeout(() => setIsCopied(false), 2000);
    } catch (err) {
      console.error("Failed to copy", err);
      alert("Failed to copy to clipboard.");
    }
  };

  return (
    // h-full and overflow-y-auto enable internal scrolling within the fixed viewport
    <div className="h-full overflow-y-auto bg-[#F5F5F7] pt-32 pb-12 px-4 flex flex-col items-center">

      {/* Main Content Card - Dark Mode for Results */}
      <motion.div
        initial={{ opacity: 0, scale: 0.95 }}
        animate={{ opacity: 1, scale: 1 }}
        transition={{ duration: 0.6, ease: [0.16, 1, 0.3, 1] }}
        className="print-content w-full max-w-xl flex-shrink-0"
      >
        <SquircleContainer
          className="w-full text-white"
          backgroundColor="black"
          cornerRadius={60} // Generous smooth radius
        >
          <div className="p-8 sm:p-10 relative">
            {/* Header with Editable Title */}
            <header className="mb-10 text-left border-b border-white/10 pb-6 relative z-10">
              <div className="mb-1 group relative">
                {isEditing ? (
                  <input
                    ref={titleInputRef}
                    value={title}
                    onChange={(e) => setTitle(e.target.value)}
                    onBlur={handleTitleSubmit}
                    onKeyDown={(e) => e.key === 'Enter' && handleTitleSubmit()}
                    className="text-4xl font-extrabold tracking-tight bg-transparent border-none outline-none p-0 w-full placeholder-gray-600 text-white selection:bg-white/30"
                    placeholder="Name your list..."
                    maxLength={MAX_TITLE_LENGTH}
                  />
                ) : (
                  <h1
                    onClick={() => setIsEditing(true)}
                    className="text-4xl font-extrabold tracking-tight cursor-text text-balance block text-white"
                  >
                    {/* Prevent orphan words by gluing the last two words with a non-breaking space */}
                    {title.includes(' ') ? (
                      <>
                        {title.slice(0, title.lastIndexOf(' '))}
                        &nbsp;
                        {title.slice(title.lastIndexOf(' ') + 1)}
                      </>
                    ) : title}
                    <button
                      onClick={(e) => {
                        e.stopPropagation();
                        setIsEditing(true);
                      }}
                      className="edit-btn inline-flex align-baseline ml-3 text-white/20 hover:text-white/60 transition-colors opacity-100 sm:opacity-0 sm:group-hover:opacity-100 focus:opacity-100 p-1"
                      aria-label="Edit title"
                      style={{ verticalAlign: 'middle', transform: 'translateY(-2px)' }}
                    >
                      <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                        <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M15.232 5.232l3.536 3.536m-2.036-5.036a2.5 2.5 0 113.536 3.536L6.5 21.036H3v-3.572L16.732 3.732z" />
                      </svg>
                    </button>
                  </h1>
                )}
              </div>
              <p className="text-gray-400 text-xs font-bold tracking-widest uppercase">
                {isPartial && <>TOP {items.length} OF {totalCount} • </>}RANKED ON {dateString}
              </p>
            </header>

            {isImageRanking ? (
              <div className="relative z-10">
                {items[0] && (
                  <motion.div
                    initial={{ opacity: 0, scale: 0.96 }}
                    animate={{ opacity: 1, scale: 1 }}
                    transition={{ delay: 0.1, duration: 0.4 }}
                    className="overflow-hidden rounded-3xl bg-white/10"
                  >
                    <div className="aspect-[4/3] bg-white/5 p-3">
                      <img src={items[0].imageUrl} alt={items[0].label} className="h-full w-full rounded-2xl object-contain" />
                    </div>
                    <div className="flex items-baseline gap-3 px-5 py-4">
                      <span className="font-mono text-lg font-bold text-yellow-400">01</span>
                      <span className="min-w-0 truncate text-2xl font-extrabold tracking-tight text-white">{items[0].label}</span>
                    </div>
                  </motion.div>
                )}

                <div className="mt-3 grid grid-cols-2 gap-3">
                  {items.slice(1, 3).map((item, index) => (
                    <motion.div
                      key={item.id}
                      initial={{ opacity: 0, y: 12 }}
                      animate={{ opacity: 1, y: 0 }}
                      transition={{ delay: 0.18 + (index * 0.07), duration: 0.35 }}
                      className="overflow-hidden rounded-2xl bg-white/10"
                    >
                      <div className="aspect-square bg-white/5 p-2">
                        <img src={item.imageUrl} alt={item.label} className="h-full w-full rounded-xl object-cover" />
                      </div>
                      <div className="flex items-baseline gap-2 px-3 py-3">
                        <span className={`font-mono text-sm font-bold ${index === 0 ? 'text-gray-300' : 'text-orange-400'}`}>{String(index + 2).padStart(2, '0')}</span>
                        <span className="min-w-0 truncate text-sm font-bold text-white">{item.label}</span>
                      </div>
                    </motion.div>
                  ))}
                </div>

                {items.length > 3 && (
                  <ol className="mt-4 space-y-2">
                    {items.slice(3).map((item, index) => (
                      <motion.li
                        key={item.id}
                        initial={{ opacity: 0, x: -10 }}
                        animate={{ opacity: 1, x: 0 }}
                        transition={{ delay: 0.3 + (index * 0.04), duration: 0.3 }}
                        className="flex items-center gap-3 rounded-2xl bg-white/5 px-3 py-2 hover:bg-white/10 transition-colors"
                      >
                        <span className="w-7 font-mono text-sm font-bold text-gray-500">{String(index + 4).padStart(2, '0')}</span>
                        <img src={item.imageUrl} alt="" className="h-11 w-11 rounded-lg object-cover bg-white/10" />
                        <span className="min-w-0 flex-1 truncate text-base font-semibold text-gray-200">{item.label}</span>
                      </motion.li>
                    ))}
                  </ol>
                )}
              </div>
            ) : (
              <ol className="list-none relative z-10 space-y-2">
                {items.map((item, index) => {
                  const isFirst = index === 0;
                  const isSecond = index === 1;
                  const isThird = index === 2;

                  let rankColor = "text-gray-500";
                  let textColor = "text-gray-300";
                  let rowBg = "bg-white/5";
                  let textSize = "text-lg";
                  let fontWeight = "font-semibold";
                  let paddingY = "py-3";

                  if (isFirst) {
                    rankColor = "text-yellow-400";
                    textColor = "text-white";
                    rowBg = "bg-white/10";
                    textSize = "text-2xl";
                    fontWeight = "font-extrabold";
                    paddingY = "py-5";
                  } else if (isSecond) {
                    rankColor = "text-gray-300";
                    textColor = "text-white";
                    textSize = "text-xl";
                    fontWeight = "font-bold";
                    paddingY = "py-4";
                  } else if (isThird) {
                    rankColor = "text-orange-400";
                    textColor = "text-white";
                    textSize = "text-xl";
                    fontWeight = "font-bold";
                    paddingY = "py-4";
                  }

                  return (
                    <motion.li
                      key={item.id}
                      initial={{ opacity: 0, x: -10 }}
                      animate={{ opacity: 1, x: 0 }}
                      transition={{ delay: 0.1 + (index * 0.05), duration: 0.4 }}
                      className={`group flex flex-col justify-center px-6 ${paddingY} rounded-2xl ${rowBg} hover:bg-white/15 transition-colors`}
                    >
                      <div className="flex items-baseline">
                        <span className={`w-10 font-mono ${isFirst ? 'text-lg' : 'text-sm'} font-bold ${rankColor}`}>
                          {(index + 1).toString().padStart(2, '0')}
                        </span>
                        <span className={`flex-1 ${textSize} ${fontWeight} tracking-tight ${textColor} truncate`}>
                          {item.label}
                        </span>
                      </div>
                    </motion.li>
                  );
                })}
              </ol>
            )}


          </div>
        </SquircleContainer>
      </motion.div>

      {isPartial && (
        <motion.p
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          transition={{ delay: 0.4, duration: 0.6 }}
          className="no-print mt-6 w-full max-w-xl flex-shrink-0 text-center text-sm font-medium text-gray-500"
        >
          {totalCount - items.length} more {totalCount - items.length === 1 ? 'item is' : 'items are'} not ranked yet.{' '}
          <button type="button" onClick={onContinue} className="font-extrabold text-black underline underline-offset-4 hover:no-underline">
            Keep ranking
          </button>
        </motion.p>
      )}

      {/* Action Bar */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.5, duration: 0.6 }}
        className="no-print mt-8 flex flex-col sm:flex-row gap-3 w-full max-w-xl flex-shrink-0"
      >
        <div className='flex gap-2 flex-1'>
          <Button onClick={onReset} variant="secondary" className="flex-1">
            New
          </Button>
          <Button onClick={onRestart} variant="secondary" className="flex-1">
            Retry
          </Button>
        </div>

        <Button
          onClick={handleCopyToClipboard}
          variant="primary"
          className="flex-[2]"
        >
          {isCopied ? (
            <span className="flex items-center gap-2">
              <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 13l4 4L19 7" />
              </svg>
              Copied!
            </span>
          ) : (
            "Copy to Clipboard"
          )}
        </Button>
      </motion.div>

    </div>
  );
};
