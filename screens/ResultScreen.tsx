import React, { useState, useRef, useEffect, useMemo } from 'react';
import { Item } from '../types';
import { Button } from '../components/Button';
import { SquircleContainer } from '../components/SquircleContainer';
import { motion } from 'framer-motion';
import { sanitizeString, MAX_TITLE_LENGTH } from '../utils/security';
import { renderRankingImage, canvasToPng, imageFileName } from '../utils/shareImage';
import { encodeListLink, siteUrl } from '../utils/shareLink';
import { compareRankings, compareKey } from '../utils/compare';

interface ResultScreenProps {
  items: Item[]; // Assumed sorted. Shorter than totalCount for a Top N.
  /** The whole list in the order it was entered, for the list link. */
  allItems: Item[];
  totalCount: number;
  /** The user's own title, if they set one. */
  title?: string;
  finishedAt?: number;
  /** A friend's order for this list (labels, best first), when it came from their link. */
  theirRanking?: string[];
  onTitleChange: (title: string | undefined) => void;
  onContinue: () => void;
  onReset: () => void;
  onRestart: () => void;
}

const CheckMark = () => (
  <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" aria-hidden="true">
    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 13l4 4L19 7" />
  </svg>
);

export const ResultScreen: React.FC<ResultScreenProps> = ({
  items, allItems, totalCount, title: customTitle, finishedAt, theirRanking, onTitleChange, onContinue, onReset, onRestart
}) => {
  // A Top N: the user stopped before every item was placed
  const isPartial = items.length < totalCount;
  const defaultTitle = isPartial ? `Your Top ${items.length}` : "Your Ranking";
  const title = customTitle ?? defaultTitle;
  const [draft, setDraft] = useState(title);
  const [isEditing, setIsEditing] = useState(false);
  const titleInputRef = useRef<HTMLInputElement>(null);
  const isImageRanking = items.some(item => item.imageUrl);

  // How this ranking compares with the friend's, when there is enough in common
  const comparison = useMemo(() => {
    if (!theirRanking || isImageRanking) return null;
    const result = compareRankings(items.map(item => item.label), theirRanking);
    return result.agreement === null ? null : result;
  }, [items, theirRanking, isImageRanking]);
  const place = (value: number) => value.toString().padStart(2, '0');
  const theirPlaceOfMyFirst = comparison && items[0] ? comparison.theirPlace.get(compareKey(items[0].label)) : undefined;

  // Which button last succeeded, for its brief "done" label, and any failure to report
  const [done, setDone] = useState<'text' | 'link' | 'image' | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [isMakingImage, setIsMakingImage] = useState(false);
  const flashDone = (what: 'text' | 'link' | 'image') => {
    setNotice(null);
    setDone(what);
    setTimeout(() => setDone(current => (current === what ? null : current)), 2000);
  };

  // The visitor's own date and time format, from when the ranking was finished
  const [dateString] = useState(() => {
    const when = new Date(finishedAt ?? Date.now());
    const date = when.toLocaleDateString(undefined, { dateStyle: 'long' });
    const time = when.toLocaleTimeString(undefined, { timeStyle: 'short' });
    return `${date} • ${time}`;
  });
  const subtitle = `${isPartial ? `Top ${items.length} of ${totalCount} • ` : ''}Ranked on ${dateString}`;

  useEffect(() => {
    if (isEditing && titleInputRef.current) {
      titleInputRef.current.focus();
      titleInputRef.current.select();
    }
  }, [isEditing]);

  const startEditing = () => {
    setDraft(title);
    setIsEditing(true);
  };

  const commitTitle = () => {
    if (!isEditing) return;
    setIsEditing(false);
    const cleanTitle = sanitizeString(draft, MAX_TITLE_LENGTH);
    // An empty or untouched title goes back to the default wording
    onTitleChange(cleanTitle === '' || cleanTitle === defaultTitle ? undefined : cleanTitle);
  };

  const cancelEditing = () => setIsEditing(false);

  const copy = async (text: string, what: 'text' | 'link') => {
    try {
      await navigator.clipboard.writeText(text);
      flashDone(what);
    } catch {
      setNotice("Couldn't copy. Your browser blocked access to the clipboard.");
    }
  };

  const handleCopyText = () => {
    const listText = items
      .map((item, index) => `${(index + 1).toString().padStart(2, '0')}. ${item.label}`)
      .join('\n');
    copy(`${title}\n${subtitle}\n\n${listText}\n\nGenerated by The Order\n${siteUrl()}`, 'text');
  };

  const handleCopyLink = async () => {
    // The link carries this ranking, best first, then anything left unranked
    const rankedIds = new Set(items.map(item => item.id));
    const ranked = items.map(item => item.label);
    const rest = allItems.filter(item => !rankedIds.has(item.id)).map(item => item.label);
    copy(await encodeListLink(ranked, rest), 'link');
  };

  // --- Picture of the ranking ---
  // Phones get the system share sheet; computers get a download.
  const [sharesNatively] = useState(
    () => typeof navigator.share === 'function' && typeof navigator.canShare === 'function' && window.matchMedia('(pointer: coarse)').matches
  );

  // The picture is drawn ahead of time. Phones only allow the share sheet to
  // open straight from a tap, and drawing first would lose that moment.
  const imageRef = useRef<{ key: string; file: File } | null>(null);
  const imageKey = `${title}|${subtitle}|${items.map(item => item.id).join('|')}`;
  const makeImage = async (): Promise<File> => {
    if (imageRef.current?.key === imageKey) return imageRef.current.file;
    const canvas = await renderRankingImage({
      title,
      subtitle,
      items,
      footer: siteUrl().replace(/^https?:\/\//, '').replace(/\/$/, '')
    });
    const file = new File([await canvasToPng(canvas)], imageFileName(title), { type: 'image/png' });
    imageRef.current = { key: imageKey, file };
    return file;
  };
  useEffect(() => {
    const timer = setTimeout(() => { makeImage().catch(() => {}); }, 400);
    return () => clearTimeout(timer);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [imageKey]);

  const downloadImage = (file: File) => {
    const url = URL.createObjectURL(file);
    const link = document.createElement('a');
    link.href = url;
    link.download = file.name;
    link.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    flashDone('image');
  };

  const handleImage = async () => {
    setIsMakingImage(true);
    try {
      const file = await makeImage();
      if (sharesNatively && navigator.canShare({ files: [file] })) {
        try {
          await navigator.share({ files: [file], title });
        } catch (err) {
          // Closing the share sheet is not a failure; anything else falls back to saving
          if ((err as DOMException)?.name !== 'AbortError') downloadImage(file);
        }
      } else {
        downloadImage(file);
      }
      setNotice(null);
    } catch {
      setNotice("Couldn't create the image. Copy the text instead.");
    } finally {
      setIsMakingImage(false);
    }
  };

  return (
    // h-full and overflow-y-auto enable internal scrolling within the fixed viewport
    <motion.div
      exit={{ opacity: 0 }}
      transition={{ duration: 0.2 }}
      className="h-full overflow-y-auto bg-page pt-32 pb-12 px-4 flex flex-col items-center"
    >

      {/* Main Content Card - Dark Mode for Results */}
      <motion.div
        initial={{ opacity: 0, scale: 0.95 }}
        animate={{ opacity: 1, scale: 1 }}
        transition={{ duration: 0.6, ease: [0.16, 1, 0.3, 1] }}
        className="print-content w-full max-w-xl flex-shrink-0"
      >
        <SquircleContainer
          className="w-full text-white"
          backgroundColor="var(--color-card)"
          cornerRadius={60} // Generous smooth radius
          shadow="high"
        >
          <div className="p-8 sm:p-10 relative">
            {/* Header with Editable Title */}
            <header className="mb-10 text-left border-b border-white/10 pb-6 relative z-10">
              <div className="mb-1 group relative">
                {isEditing ? (
                  <input
                    ref={titleInputRef}
                    value={draft}
                    onChange={(e) => setDraft(e.target.value)}
                    onBlur={commitTitle}
                    onKeyDown={(e) => {
                      if (e.key === 'Enter') commitTitle();
                      // Escape leaves the title as it was
                      else if (e.key === 'Escape') cancelEditing();
                    }}
                    aria-label="Title of your ranking"
                    className="text-4xl font-extrabold tracking-tight bg-transparent border-none outline-none p-0 w-full placeholder-gray-600 text-white selection:bg-white/30"
                    placeholder="Name your list..."
                    maxLength={MAX_TITLE_LENGTH}
                  />
                ) : (
                  <h1
                    onClick={startEditing}
                    className="text-4xl font-extrabold tracking-tight cursor-text text-balance block text-white break-words"
                  >
                    {/* Prevent orphan words by gluing the last two words with a non-breaking space */}
                    {title.includes(' ') ? (
                      <>
                        {title.slice(0, title.lastIndexOf(' '))}
                        &nbsp;
                        {title.slice(title.lastIndexOf(' ') + 1)}
                      </>
                    ) : title}
                    <button
                      onClick={(e) => {
                        e.stopPropagation();
                        startEditing();
                      }}
                      className="edit-btn no-print inline-flex align-baseline ml-2 rounded-lg p-2 text-white/40 hover:text-white/80 transition-colors"
                      aria-label="Edit title"
                      style={{ verticalAlign: 'middle', transform: 'translateY(-2px)' }}
                    >
                      <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                        <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M15.232 5.232l3.536 3.536m-2.036-5.036a2.5 2.5 0 113.536 3.536L6.5 21.036H3v-3.572L16.732 3.732z" />
                      </svg>
                    </button>
                  </h1>
                )}
              </div>
              <p className="text-gray-400 text-xs font-bold tracking-widest uppercase">
                {subtitle}
              </p>
            </header>

            {isImageRanking ? (
              <div className="relative z-10">
                {items[0] && (
                  <motion.div
                    initial={{ opacity: 0, scale: 0.96 }}
                    animate={{ opacity: 1, scale: 1 }}
                    transition={{ delay: 0.1, duration: 0.4 }}
                    className="overflow-hidden rounded-3xl bg-white/10"
                  >
                    <div className="aspect-[4/3] bg-white/5 p-3">
                      <img src={items[0].imageUrl} alt={items[0].label} className="h-full w-full rounded-2xl object-contain" />
                    </div>
                    <div className="flex items-baseline gap-3 px-5 py-4">
                      <span className="font-mono text-lg font-bold text-yellow-400">01</span>
                      <span className="min-w-0 break-words text-2xl font-extrabold tracking-tight text-white">{items[0].label}</span>
                    </div>
                  </motion.div>
                )}

                <div className="mt-3 grid grid-cols-2 gap-3">
                  {items.slice(1, 3).map((item, index) => (
                    <motion.div
                      key={item.id}
                      initial={{ opacity: 0, y: 12 }}
                      animate={{ opacity: 1, y: 0 }}
                      transition={{ delay: 0.18 + (index * 0.07), duration: 0.35 }}
                      className="overflow-hidden rounded-2xl bg-white/10"
                    >
                      <div className="aspect-square bg-white/5 p-2">
                        <img src={item.imageUrl} alt={item.label} className="h-full w-full rounded-xl object-cover" />
                      </div>
                      <div className="flex items-baseline gap-2 px-3 py-3">
                        <span className={`font-mono text-sm font-bold ${index === 0 ? 'text-gray-300' : 'text-orange-400'}`}>{String(index + 2).padStart(2, '0')}</span>
                        <span className="min-w-0 break-words text-sm font-bold text-white">{item.label}</span>
                      </div>
                    </motion.div>
                  ))}
                </div>

                {items.length > 3 && (
                  <ol className="mt-4 space-y-2">
                    {items.slice(3).map((item, index) => (
                      <motion.li
                        key={item.id}
                        initial={{ opacity: 0, x: -10 }}
                        animate={{ opacity: 1, x: 0 }}
                        transition={{ delay: 0.3 + (index * 0.04), duration: 0.3 }}
                        className="flex items-center gap-3 rounded-2xl bg-white/5 px-3 py-2 hover:bg-white/10 transition-colors"
                      >
                        <span className="w-7 flex-none font-mono text-sm font-bold text-gray-400">{String(index + 4).padStart(2, '0')}</span>
                        <img src={item.imageUrl} alt="" className="h-11 w-11 rounded-lg object-cover bg-white/10" />
                        <span className="min-w-0 flex-1 break-words text-base font-semibold text-gray-200">{item.label}</span>
                      </motion.li>
                    ))}
                  </ol>
                )}
              </div>
            ) : (
              <>
              {comparison && (
                <section aria-label="Compared with your friend" className="relative z-10 -mt-4 mb-6">
                  <p className="text-white">
                    <span className="text-5xl font-extrabold tracking-tight">{Math.round(comparison.agreement! * 100)}%</span>
                    <span className="ml-3 text-base font-semibold text-gray-300">the same as your friend</span>
                  </p>
                  <p className="mt-2 text-sm font-medium leading-relaxed text-gray-400">
                    Of every two items, that is how often you both put the same one first.{' '}
                    {comparison.sameTop
                      ? 'You agree on first place.'
                      : theirPlaceOfMyFirst
                        ? `Your first place is their number ${theirPlaceOfMyFirst}.`
                        : 'Your friend did not rank your first place.'}
                    {comparison.biggestGap && (
                      <> Biggest gap: {comparison.biggestGap.label} (you {place(comparison.biggestGap.mine)}, friend {place(comparison.biggestGap.theirs)}).</>
                    )}
                    {comparison.common < items.length && (
                      <> Compared on the {comparison.common} items you both ranked.</>
                    )}
                  </p>
                  <div className="mt-5 flex justify-between px-6 text-[0.6875rem] font-bold uppercase tracking-widest text-gray-500">
                    <span>You</span>
                    <span>Friend’s place</span>
                  </div>
                </section>
              )}
              <ol className="list-none relative z-10 space-y-2">
                {items.map((item, index) => {
                  const isFirst = index === 0;
                  const isSecond = index === 1;
                  const isThird = index === 2;

                  let rankColor = "text-gray-400";
                  let textColor = "text-gray-300";
                  let rowBg = "bg-white/5";
                  let textSize = "text-lg";
                  let fontWeight = "font-semibold";
                  let paddingY = "py-3";

                  if (isFirst) {
                    rankColor = "text-yellow-400";
                    textColor = "text-white";
                    rowBg = "bg-white/10";
                    textSize = "text-2xl";
                    fontWeight = "font-extrabold";
                    paddingY = "py-5";
                  } else if (isSecond) {
                    rankColor = "text-gray-300";
                    textColor = "text-white";
                    textSize = "text-xl";
                    fontWeight = "font-bold";
                    paddingY = "py-4";
                  } else if (isThird) {
                    rankColor = "text-orange-400";
                    textColor = "text-white";
                    textSize = "text-xl";
                    fontWeight = "font-bold";
                    paddingY = "py-4";
                  }

                  return (
                    <motion.li
                      key={item.id}
                      initial={{ opacity: 0, x: -10 }}
                      animate={{ opacity: 1, x: 0 }}
                      transition={{ delay: 0.1 + (index * 0.05), duration: 0.4 }}
                      className={`group flex flex-col justify-center px-6 ${paddingY} rounded-2xl ${rowBg} hover:bg-white/15 transition-colors`}
                    >
                      <div className="flex items-baseline">
                        <span className={`w-10 flex-none font-mono ${isFirst ? 'text-lg' : 'text-sm'} font-bold ${rankColor}`}>
                          {(index + 1).toString().padStart(2, '0')}
                        </span>
                        <span className={`min-w-0 flex-1 ${textSize} ${fontWeight} leading-snug tracking-tight ${textColor} break-words`}>
                          {item.label}
                        </span>
                        {comparison && (() => {
                          const theirs = comparison.theirPlace.get(compareKey(item.label));
                          const mine = index + 1;
                          return (
                            <span
                              className={`ml-3 flex-none whitespace-nowrap font-mono text-sm font-bold ${theirs === mine ? 'text-gray-500' : 'text-gray-300'}`}
                              aria-label={theirs ? `Your friend's place: ${theirs}` : 'Your friend did not rank this'}
                            >
                              {theirs && theirs !== mine && (
                                <span aria-hidden="true" className="mr-1.5 text-xs text-gray-500">{theirs < mine ? '▲' : '▼'}</span>
                              )}
                              {theirs ? place(theirs) : '–'}
                            </span>
                          );
                        })()}
                      </div>
                    </motion.li>
                  );
                })}
              </ol>
              </>
            )}

          </div>
        </SquircleContainer>
      </motion.div>

      {isPartial && (
        <motion.p
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          transition={{ delay: 0.4, duration: 0.6 }}
          className="no-print mt-6 w-full max-w-xl flex-shrink-0 text-center text-sm font-medium text-muted"
        >
          {totalCount - items.length} more {totalCount - items.length === 1 ? 'item is' : 'items are'} not ranked yet.{' '}
          <button type="button" onClick={onContinue} className="font-extrabold text-ink underline underline-offset-4 hover:no-underline">
            Keep ranking
          </button>
        </motion.p>
      )}

      {/* Actions: the picture is the main one; everything else is secondary and flat */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.5, duration: 0.6 }}
        className="no-print mt-8 w-full max-w-xl flex-shrink-0"
      >
        <Button onClick={handleImage} variant="primary" fullWidth disabled={isMakingImage}>
          {done === 'image' ? (
            <span className="flex items-center gap-2"><CheckMark /> Saved</span>
          ) : sharesNatively ? 'Share image' : 'Save image'}
        </Button>

        <div className="mt-3 grid grid-cols-2 gap-3">
          <Button onClick={handleCopyText} variant="secondary" className={isImageRanking ? 'col-span-2' : ''}>
            {done === 'text' ? <span className="flex items-center gap-2"><CheckMark /> Copied</span> : 'Copy text'}
          </Button>
          {!isImageRanking && (
            <Button onClick={handleCopyLink} variant="secondary" title="Copy a link that lets someone else rank this list and compare with you">
              {done === 'link' ? <span className="flex items-center gap-2"><CheckMark /> Copied</span> : 'Copy list link'}
            </Button>
          )}
          <Button onClick={onRestart} variant="secondary">
            Rank again
          </Button>
          <Button onClick={onReset} variant="secondary">
            New list
          </Button>
        </div>

        <p role="status" className="mt-3 min-h-5 text-center text-sm font-semibold text-danger">
          {notice}
        </p>
        {!isImageRanking && (
          <p className="text-center text-xs font-medium leading-relaxed text-muted">
            The list link lets a friend rank this list. When they finish, they see how their order compares with yours.
          </p>
        )}
      </motion.div>

    </motion.div>
  );
};
